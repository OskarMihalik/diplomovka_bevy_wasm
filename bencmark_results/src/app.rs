//! The whole bevy_diplomovka app in bench mode (rendering_runner, `matrices/app.csv`): reads
//! fps.csv and load.csv, which have the app's own columns, and compares the app with the Bevy
//! rendering benchmark, which renders the same model with the same camera but without the UI,
//! picking and outlines. Writes `tables/app.tex`.

use serde::Deserialize;
use std::fmt::Write as _;
use std::path::Path;

use crate::data::{MODELS, Measurement, Platform, RESOLUTION};
use crate::stats::{Summary, welch};
use crate::{format_p, mean_sd, tex_escape};

#[derive(Deserialize)]
struct Row {
    camera_distance: f64,
    gpu: String,
    browser: String,
    resolution: String,
    model_name: String,
    // fps.csv
    #[serde(default)]
    avg_fps: f64,
    // load.csv
    #[serde(default)]
    total_ms: f64,
}

pub struct AppMeasurement {
    model: usize,
    native: bool,
    row: Row,
}

/// Rows at the paper's resolution on the integrated GPU; fps rows also at the model's distance
pub fn read(path: &Path, check_distance: bool) -> Result<Vec<AppMeasurement>, String> {
    let mut reader = csv::ReaderBuilder::new()
        .flexible(true)
        .from_path(path)
        .map_err(|e| format!("{}: {e}", path.display()))?;
    let mut measurements = Vec::new();
    let mut skipped = 0;
    for row in reader.deserialize::<Row>() {
        // rows from before the camera_distance column don't parse
        let Ok(row) = row else {
            skipped += 1;
            continue;
        };
        let model = MODELS.iter().position(|m| m.file == row.model_name);
        match model {
            Some(model)
                if row.resolution == RESOLUTION
                    && !row.gpu.contains("NVIDIA")
                    && (!check_distance
                        || (row.camera_distance - MODELS[model].distance).abs() < 0.01) =>
            {
                measurements.push(AppMeasurement {
                    model,
                    native: row.browser == "native",
                    row,
                })
            }
            _ => skipped += 1,
        }
    }
    eprintln!(
        "{}: {} rows used, {skipped} skipped (other settings, distance, unknown model or old columns)",
        path.display(),
        measurements.len()
    );
    Ok(measurements)
}

fn app_summary(rows: &[AppMeasurement], model: usize, native: bool, f: fn(&Row) -> f64) -> Option<Summary> {
    let values: Vec<f64> = rows
        .iter()
        .filter(|m| m.model == model && m.native == native)
        .map(|m| f(&m.row))
        .collect();
    Summary::of(&values)
}

fn benchmark_summary(fps: &[Measurement], model: usize, platform: Platform) -> Option<Summary> {
    let values: Vec<f64> = fps
        .iter()
        .filter(|m| m.model == model && m.platform == platform)
        .map(|m| m.row.avg_fps)
        .collect();
    Summary::of(&values)
}

/// Average fps of the app on the web and natively, the difference to the Bevy rendering
/// benchmark (Welch's t-test), and the app's load time
pub fn table(app_fps: &[AppMeasurement], app_load: &[AppMeasurement], fps: &[Measurement]) -> String {
    let mut tex = String::from(
        "% generated by bencmark_results, don't edit\n\
         % average fps, mean $\\pm$ sd; \\Delta = (app - rendering benchmark) / rendering benchmark;\n\
         % load time in s, mean $\\pm$ sd\n\
         \\begin{tabular}{lrrrrrrrr}\n\\toprule\n\
         & \\multicolumn{3}{c}{Client (Wasm)} & \\multicolumn{3}{c}{Client (native)} & \\multicolumn{2}{c}{Load time (s)} \\\\\n\
         \\cmidrule(lr){2-4} \\cmidrule(lr){5-7} \\cmidrule(lr){8-9}\n\
         Model & FPS & $\\Delta$ (\\%) & $p$ & FPS & $\\Delta$ (\\%) & $p$ & Wasm & native \\\\\n\\midrule\n",
    );
    for (i, model) in MODELS.iter().enumerate() {
        if !app_fps.iter().any(|m| m.model == i) {
            continue;
        }
        let mut cells = Vec::new();
        for (native, platform) in [(false, Platform::BevyWasm), (true, Platform::BevyNative)] {
            match app_summary(app_fps, i, native, |r| r.avg_fps) {
                Some(app) => {
                    cells.push(mean_sd(app, 1));
                    match benchmark_summary(fps, i, platform).and_then(|b| welch(app, b)) {
                        Some(w) => {
                            cells.push(format!("{:+.1}", w.diff_percent));
                            cells.push(format_p(w.p));
                        }
                        None => cells.extend(["--".to_string(), "--".into()]),
                    }
                }
                None => {
                    let reason = if model.wasm_oom && !native { "OOM" } else { "--" };
                    cells.extend([reason.to_string(), "--".into(), "--".into()]);
                }
            }
        }
        for native in [false, true] {
            cells.push(match app_summary(app_load, i, native, |r| r.total_ms / 1000.) {
                Some(s) => mean_sd(s, 2),
                None if model.wasm_oom && !native => "OOM".into(),
                None => "--".into(),
            });
        }
        let _ = writeln!(tex, "{} & {} \\\\", tex_escape(model.name), cells.join(" & "));
    }
    tex.push_str("\\bottomrule\n\\end{tabular}\n");
    tex
}
